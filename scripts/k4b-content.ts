const DEEL2 = r`Alleen deel 2 van de driedeling speelt hier: bereken de goede integraal.`
const DEEL2_BEPAALD = `${DEEL2} Eerst een primitieve zoeken, daarna de grenzen invullen. Het antwoord blijft exact.`
const DRIEDELING = r`Hier spelen alle drie de delen van de driedeling: eerst het verhaaltje vertalen naar een integraal (deel 1), dan die integraal berekenen (deel 2), en daarna nog iets doen met de uitkomst (deel 3).`
const CONTROLE = r`Controle: differentieer $F$ en je krijgt $f$ terug.`

const SCHIL_NEG = r`Buitenste schil: een breuk met een kwadratische noemer. Bereken eerst de discriminant. $D < 0$, dus de noemer heeft geen nulpunten: schrijf de teller als een veelvoud van de afgeleide van de noemer plus een constante. Het eerste stuk geeft een logaritme, het tweede een arctangens.`
const SCHIL_NUL = r`Buitenste schil: een breuk met een kwadratische noemer. $D = 0$, dus de noemer is een kwadraat van een lineaire factor. Schrijf de teller als een veelvoud van die factor plus een constante: er komt een logaritme uit en een breuk met het kwadraat in de noemer.`
const SCHIL_POS = r`Buitenste schil: een breuk met een kwadratische noemer. $D > 0$, dus de noemer ontbindt in twee verschillende lineaire factoren. Splits de breuk in twee stukken; elk stuk geeft een logaritme.`

function primitief(schil: string, s: { splits: string; regel: string; antwoord: string }): Steps {
  return [`${DEEL2} ${schil}`, s.splits, s.regel, `${s.antwoord} ${CONTROLE}`]
}

function bepaald(schil: string, s: { splits: string; primitieve: string; invullen: string }): Steps {
  return [`${DEEL2_BEPAALD} ${schil}`, s.splits, s.primitieve, s.invullen]
}

function oppervlakte(s: { integraal: string; splits: string; primitieve: string; uitkomst: string }): Steps {
  return [`${DRIEDELING} ${s.integraal}`, s.splits, s.primitieve, s.uitkomst]
}

